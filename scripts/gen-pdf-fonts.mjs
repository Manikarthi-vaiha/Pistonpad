// Regenerates src/lib/pdf/fonts.generated.ts — the fonts embedded in invoice PDFs.
// Noto Sans (latin) for text, Noto Sans Devanagari for the ₹ sign. Run: node scripts/gen-pdf-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
const dir = "node_modules/@fontsource/noto-sans/files";
const b64 = (f) => readFileSync(`${dir}/${f}`).toString("base64");
const out = `// Generated by scripts/gen-pdf-fonts.mjs — do not edit. Noto Sans, SIL Open Font License 1.1.
export const NOTO_400 = "${b64("noto-sans-latin-400-normal.woff")}";
export const NOTO_700 = "${b64("noto-sans-latin-700-normal.woff")}";
export const NOTO_DEVA_400 = "${b64("noto-sans-devanagari-400-normal.woff")}";
export const NOTO_DEVA_700 = "${b64("noto-sans-devanagari-700-normal.woff")}";
`;
writeFileSync("src/lib/pdf/fonts.generated.ts", out);
console.log("wrote src/lib/pdf/fonts.generated.ts", out.length, "bytes");
